const express=require('express');
const {asyncHandler}=require('../utils/asyncHandler');
const {serviceAuth}=require('../security/serviceAuth');
const controller=require('./internal.controller');
const {validateLookupQuery,validateUserIdParam,validateCredentialBody,validatePasswordUpdateBody}=require('./internal.validation');
const router=express.Router();router.use(serviceAuth);
router.get('/users/lookup',validateLookupQuery,asyncHandler(controller.lookupUser));
router.post('/users/:id/verify-credentials',validateUserIdParam,validateCredentialBody,asyncHandler(controller.verifyCredentials));
router.patch('/users/:id/password-hash',validateUserIdParam,validatePasswordUpdateBody,asyncHandler(controller.patchPasswordHash));
router.get('/users/:id',validateUserIdParam,asyncHandler(controller.getInternalUser));
module.exports=router;